import fs from 'node:fs/promises';
import { clampChroma, formatHex } from 'culori';

const hues = { violet: 300, blue: 260, rose: 350, orange: 55 };
const steps = { 950: [0.23, 0.035], 700: [0.43, 0.10], 500: [0.64, 0.18], 300: [0.79, 0.12], 100: [0.91, 0.045] };
let css = '/* Generated by scripts/build-palette.mjs in OKLCH; emitted as sRGB hex. */\n:root {\n';
for (const [name, h] of Object.entries(hues)) for (const [step, [l, c]] of Object.entries(steps)) {
  css += `  --${name}-${step}: ${formatHex(clampChroma({ mode: 'oklch', l, c, h }, 'oklch', 'rgb'))};\n`;
}
css += '}\n';
for (const name of Object.keys(hues)) css += `[data-accent="${name}"] {\n  --accent-soft: var(--${name}-950);\n  --accent-border: var(--${name}-700);\n  --chart-soft: var(--${name}-500);\n  --accent-solid: var(--${name}-300);\n  --accent-text: var(--${name}-100);\n  --accent-contrast: var(--background);\n}\n`;
await fs.writeFile('src/palette.css', css);
